"""Prepare actual TrueType outlines for the embedded runtime rasterizer.
Only the PDP-11's printable ASCII repertoire is retained. Components are
flattened into ordinary TrueType quadratic contours; no pixels are generated.
The Pico chooses the face and rasterizes at runtime. FontTools is host-only.
Derived fonts are renamed, preserving their OFL copyright/licence records.
"""
from pathlib import Path
from io import BytesIO
import argparse
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
ROOT=Path(__file__).resolve().parents[1]
FONTS=[('TerminalSans','lato/Lato-Regular.ttf'),('TerminalMono','jetbrainsmono/JetBrainsMono-Regular.ttf')]
OUT=ROOT/'J11_18MHz_KDJ11_BF/outputs/truetype_assets.pmi'
def generate():
 lines=['; TrueType outlines, NOT rasterized glyphs. Generated by tools/font_pack.py.',
        '; Sources and OFL notices: fonts/source/lato and fonts/source/jetbrainsmono.']
 for face,path in FONTS:
  f=TTFont(ROOT/'fonts/source'/path,recalcTimestamp=False)
  o=subset.Options();o.hinting=False;o.layout_features=[]
  z=subset.Subsetter(options=o);z.populate(unicodes=range(32,127));z.subset(f)
  gs=f.getGlyphSet()
  for name in f.getGlyphOrder():
   if f['glyf'][name].isComposite():
    recording=DecomposingRecordingPen(gs);gs[name].draw(recording)
    pen=TTGlyphPen(None);recording.replay(pen);f['glyf'][name]=pen.glyph()
  for tag in list(f.keys()):
   if tag not in ['GlyphOrder','cmap','head','hhea','hmtx','maxp','loca','glyf','name','OS/2','post']:del f[tag]
  for n in f['name'].names:
   if n.nameID in [1,3,4,6,16,17]:n.string=(face if n.nameID!=17 else 'Regular').encode(n.getEncoding())
  stream=BytesIO();f.save(stream);data=stream.getvalue()
  lines += ['#TT_%s_BYTES = %d'%(face.upper(),len(data)),'DataSection','Tt%s:'%face]
  for i in range(0,len(data),40):lines.append('  Data.a '+','.join(str(x) for x in data[i:i+40]))
  lines.append('EndDataSection')
 return '\n'.join(lines)+'\n'
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();text=generate()
 if a.check:
  if OUT.read_text(encoding='ascii').replace('\r\n','\n')!=text:raise SystemExit('TrueType assets need regeneration')
  print('TrueType outline assets current')
 else:OUT.write_text(text,encoding='ascii',newline='\n');print('wrote',OUT)

if __name__=='__main__': main()
