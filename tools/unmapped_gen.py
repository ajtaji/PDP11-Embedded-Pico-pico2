"""Build the RP2350 unmapped loop from the shared instruction definitions.
Use --preview for a separately named loop beside the checked-in implementation.
"""
from pathlib import Path
import re,sys
from asm_mov_gen import TAIL,U0,U1,G0,G1
from mmu_gen import base_rel
from cpu_state_layout import forward
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'J11_18MHz_KDJ11_BF/pico/instructions.pico'


def tail(synced=False,trap=False):
 s=''
 if synced:s+='    ldr r1, =global_reg\n    ldr r0, [r1, #28]\n    mov r9, r0\n'
 if synced or trap:s+='    ldr r1, =global_trapvector\n    ldr r1, [r1]\n    cmp r1, #0\n    bne __ul_cpurun_slowtail\n'
 s+='    subs.w r11, r11, #1\n    beq __ul_cpurun_runend\n'
 if not synced:s+='    mov r0, r9\n'
 s+='    movw r1, #RAM16\n    cmp r0, r1\n    bhs __ul_cpurun_slowfetch\n'
 if synced:s+='    lsls r1, r0, #31\n    bne __ul_cpurun_slowfetch\n'
 s+='''    ldr r1, =global_mem
    ldrh r2, [r1, r0]
    mov r8, r2
    adds.w r9, r9, #2
    lsrs r2, r2, #3
    lsls r2, r2, #2
    ldr r1, =global_optable
    ldr r1, [r1, r2]
    bx r1
'''
 return s


def generate(preview=False):
 s=SRC.read_text();s=s[s.index('Global Dim OpTable.Label'):]
 s=s.replace('ProcedureRAM.i CpuRun(n.i)','Procedure.i CpuRun(n.i)',1)
 # Unmapped addresses stop before the I/O page, even with more physical RAM.
 n=s.count(TAIL);assert n>=40,n;s=s.replace(TAIL,tail())
 s=s.replace('#RAM_BYTES','#RAM16').replace('__eaw1','__eau').replace('__eab1','__eaub')
 # Retain the RP2350's complete seven-mode EA helpers, including deferred modes.
 a=s.rfind(U0+G0,0,s.index('__eau:\n'));assert a>=0
 b=s.index(G1+U1,a)+len(G1+U1)
 s=s[:a]+(ROOT/'tools/unmapped_ea.pico2.in').read_text()+s[b:]
 for name,sync,tr in [('NextSynced',True,False),('NextNative',False,False),('NextNativeTrap',False,True)]:
  p=r'(?m)^Macro '+name+r'\(\)\n[\s\S]*?^EndMacro\n';m=re.search(p,s);assert m,name
  text='CompilerIf #ASM_TAILS = 1\nMacro '+name+'()\n  ASM Uses PC, Op, RunLeft\n'+tail(sync,tr)+'  EndASM\nEndMacro\nCompilerElse\n'+m[0]+'CompilerEndIf\n'
  s=s[:m.start()]+text+s[m.end():]
 # The MOV test mirrors are not needed for production dispatch.
 s=re.sub(r'(?m)(?:^  Mov(?:Asm|Ref)\(\d+\) = [^\n]*\n)+',lambda m:'CompilerIf #DISK_BACKEND = 0\n'+m[0]+'CompilerEndIf\n',s)
 s=base_rel(s,mapped=False)
 s=forward(s,native_base=True)
 # Immediate bounds are a single Thumb-2 instruction instead of a literal read.
 s=re.sub(r'ldr (r[0-3]), =#RAM16',r'movw \1, #RAM16',s)
 defs='''CompilerIf #DISK_BACKEND = 0
Global Dim MovAsm.Label(7)
Global Dim MovRef.Label(7)
Global Dim FastAsm.Label(42)
Global Dim FastRef.Label(42)
CompilerEndIf
'''
 s=defs+s
 if preview:
  names=['CpuRun','OpTable','OpTableReady','Ops','FillFrom','FillCount','BuildOpcodeTable']
  rename={x:x+'U' for x in names}
  rename.update({x:'U'+x for x in ['MovAsm','MovRef','FastAsm','FastRef']})
  rename.update({m[1]:m[1]+'U' for m in re.finditer(r'(?m)^Macro (\w+)\(',s)})
  s=re.sub(r'\b('+ '|'.join(sorted(rename,key=len,reverse=True))+r')\b',lambda m:rename[m[0]],s)
  s=s.replace('global_optable','global_optableu').replace('__ul_cpurun_','__ul_cpurunu_')
  s=s.replace('__t1_','__u2_').replace('__um','__u2m').replace('__imx1_','__u2imx_').replace('__ix_','__u2ix_')
  s=re.sub(r'__(?:eaub|eau)(?=\b|_)',lambda m:m[0]+'u',s)
 return '; GENERATED by tools/unmapped_gen.py from pico/instructions.pico.\n; RP2350: Thumb-2 tails, fixed CPU-state offsets, native instruction paths.\n'+s

def generate_check():
 head=(ROOT/'J11_18MHz_KDJ11_BF/pico2/asm_check.pico2').read_text()
 head=head[:head.index('#CLOCK_KHZ')]
 body=(ROOT/'J11_18MHz_KDJ11_BF/pico/asm_check.pico').read_text()
 body=body[body.index('#CLOCK_KHZ'):].replace('#CLOCK_KHZ = 200000','#CLOCK_KHZ = 150000')
 body=body.replace('  EaWordBody()','  ProcedureReturn EaWord(spec)',1)
 body=body.replace('__eaw1','__eau').replace('__eab1','__eaub')
 body=re.sub(r'\br5\b','r6',body).replace('push {r6}','push {r3, r6}').replace('pop {r6}','pop {r3, r6}')
 body=body.replace("the Pico's unmapped", "the Pico 2's unmapped")
 return '; GENERATED by tools/unmapped_gen.py --tests from pico/asm_check.pico.\n'+head+forward(body)

if __name__=='__main__':
 preview='--preview' in sys.argv
 tests='--tests' in sys.argv
 p=Path(sys.argv[sys.argv.index('--out')+1]) if '--out' in sys.argv else ROOT/'J11_18MHz_KDJ11_BF/pico2'/('instructions_unmapped_candidate.pico2' if preview else 'instructions.pico2')
 if tests:p=ROOT/'J11_18MHz_KDJ11_BF/pico2/unmapped_check.pico2'
 want=generate_check() if tests else generate(preview)
 if '--check' in sys.argv:
  if p.read_text()!=want:raise SystemExit('unmapped_gen: output is stale')
 else:p.write_text(want)
 print('unmapped_gen:',p.name,'current')
